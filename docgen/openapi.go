// Spec is a generated OpenAPI document.
// Spec 是一份已生成的 OpenAPI 文档，内部保存可直接编码为 YAML 或 JSON 的映射。
type Spec struct {
	data map[string]any
}

// Build generates a document from routes.
// Build 由路由描述符生成文档：按完整部署路径与 HTTP 方法稳定排序，完整路径
// 优先取 Group.Add 写入描述符的前缀，Config.Prefixes 可把该前缀替换为另一个
// 部署基址；未分组路由直接以 Config.Prefixes 为前缀。同时校验 operationID
// 非空且唯一、路径以 / 开头、同一方法加路径不重复。
func Build(routes []endpoint.Descriptor, cfg Config) (*Spec, error) {
	cfg = cfg.withDefaults()
	ctx := newContext(cfg)
	ctx.components["CommonEnvelope"] = commonEnvelope()
	ctx.components["CommonErrorEnvelope"] = commonErrorEnvelope()

	type builtRoute struct {
		desc endpoint.Descriptor
		spec endpoint.Spec
		path string
	}
	ordered := make([]builtRoute, 0, len(routes))
	for _, desc := range routes {
		spec := desc.Spec()
		ordered = append(ordered, builtRoute{desc: desc, spec: spec, path: cfg.routePath(spec)})
	}
	sort.SliceStable(ordered, func(i, j int) bool {
		if ordered[i].path != ordered[j].path {
			return ordered[i].path < ordered[j].path
		}
		return ordered[i].spec.Method < ordered[j].spec.Method
	})

	paths := make(map[string]any)
	seenOperation := make(map[string]bool, len(ordered))
	seenRoute := make(map[string]bool, len(ordered))
	needAuth := false
	for _, entry := range ordered {
		spec := entry.spec
		if spec.OperationID == "" {
			return nil, fmt.Errorf("docgen: %s %s has no operation id", spec.Method, spec.Path)
		}
		if seenOperation[spec.OperationID] {
			return nil, fmt.Errorf("docgen: duplicate operation id %q", spec.OperationID)
		}
		seenOperation[spec.OperationID] = true
		if !strings.HasPrefix(spec.Path, "/") {
			return nil, fmt.Errorf("docgen: %s path %q must start with /", spec.OperationID, spec.Path)
		}
		method := strings.ToLower(spec.Method)
		key := method + " " + entry.path
		if seenRoute[key] {
			return nil, fmt.Errorf("docgen: duplicate route %s", key)
		}
		seenRoute[key] = true

		if spec.Auth == endpoint.AuthRequired || spec.Auth == endpoint.AuthOptional {
			needAuth = true
		}
		op, err := ctx.operation(entry.desc, spec)
		if err != nil {
			return nil, err
		}
		item, _ := paths[entry.path].(map[string]any)
		if item == nil {
			item = make(map[string]any)
			paths[entry.path] = item
		}
		item[method] = op
	}

	info := map[string]any{
		"title":   cfg.Title,
		"version": cfg.Version,
	}
	if cfg.Description != "" {
		info["description"] = cfg.Description
	}
	doc := map[string]any{
		"openapi": "3.0.3",
		"info":    info,
		"paths":   paths,
	}

	if len(cfg.Servers) > 0 {
		servers := make([]any, 0, len(cfg.Servers))
		for _, server := range cfg.Servers {
			item := map[string]any{"url": server.URL}
			if server.Description != "" {
				item["description"] = server.Description
			}
			servers = append(servers, item)
		}
		doc["servers"] = servers
	}

	components := make(map[string]any)
	for name, schema := range ctx.components {
		if schema == nil {
			return nil, fmt.Errorf("docgen: component %q was not completed", name)
		}
	}
	components["schemas"] = ctx.components
	if schemes := securitySchemes(cfg, needAuth); len(schemes) > 0 {
		components["securitySchemes"] = schemes
	}
	if len(components["schemas"].(map[string]any)) > 0 || len(components) > 1 {
		doc["components"] = components
	}
	return &Spec{data: doc}, nil
}

// YAML renders the document with a generated-file header.
// YAML 渲染文档，并在首行写入 Code generated 头，提醒该文件是生成物、不要手改。
func (s *Spec) YAML() ([]byte, error) {
	if s == nil {
		return nil, errors.New("docgen: nil spec")
	}
	var buf bytes.Buffer
	buf.WriteString("# Code generated by gofy-openapi. DO NOT EDIT.\n")
	encoder := yaml.NewEncoder(&buf)
	encoder.SetIndent(2)
	if err := encoder.Encode(s.data); err != nil {
		return nil, fmt.Errorf("docgen: encode yaml: %w", err)
	}
	if err := encoder.Close(); err != nil {
		return nil, fmt.Errorf("docgen: close yaml encoder: %w", err)
	}
	return buf.Bytes(), nil
}

// JSON renders the document.
// JSON 以两空格缩进渲染文档，并补一个结尾换行，便于与生成物逐字节比对。
func (s *Spec) JSON() ([]byte, error) {
	if s == nil {
		return nil, errors.New("docgen: nil spec")
	}
	data, err := json.MarshalIndent(s.data, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("docgen: encode json: %w", err)
	}
	return append(data, '\n'), nil
}

// Validate parses and validates the generated document.
// Validate 先把文档编码为 JSON，再用 kin-openapi 解析并校验；外部 $ref 被禁止，
// 因此校验不会访问网络。
func (s *Spec) Validate(ctx context.Context) error {
	if s == nil {
		return errors.New("docgen: nil spec")
	}
	data, err := s.JSON()
	if err != nil {
		return err
	}
	loader := openapi3.NewLoader()
	loader.IsExternalRefsAllowed = false
	doc, err := loader.LoadFromData(data)
	if err != nil {
		return fmt.Errorf("docgen: load openapi: %w", err)
	}
	if err := doc.Validate(ctx); err != nil {
		return fmt.Errorf("docgen: validate openapi: %w", err)
	}
	return nil
}

// FilterByService keeps routes whose tags match service ("demoservice") or its
// module part ("order").
// FilterByService 保留 tag 等于 service（如 "demoservice"）或其模块部分
// （如 "order"，即第一个点之前的部分）的路由；service 为空时不筛选。
func FilterByService(routes []endpoint.Descriptor, service string) []endpoint.Descriptor {
	service = strings.TrimSpace(service)
	if service == "" {
		return routes
	}
	module := service
	if i := strings.IndexByte(service, '.'); i >= 0 {
		module = service[:i]
	}
	out := make([]endpoint.Descriptor, 0, len(routes))
	for _, desc := range routes {
		for _, tag := range desc.Spec().Tags {
			if tag == service || tag == module {
				out = append(out, desc)
				break
			}
		}
	}
	return out
}

// prefixFor returns the deployment prefix for a set of tags. One service may
// mount several deployment prefixes (order /api/v1/order, product
// /api/v1/product); the prefix table tells the service name apart from
// "service.group" keys such as demoservice and demoservice.product. Matching runs
// in two steps: an exact tag/key match wins, taking the longest key, i.e. the
// most specific group prefix; when nothing matches exactly, a tag equal to the
// service name (the part before the first dot) matches, as a fallback for routes
// carrying only the service tag, picking the first key in lexicographic order,
// i.e. the service-level key.
// prefixFor 返回一组标签对应的部署前缀。
//
// 一个服务可以挂多个部署前缀（订单 /api/v1/order、产品 /api/v1/product），
// 前缀表用「服务名」与「服务名.分组名」区分，例如 demoservice 和
// demoservice.product。匹配分两步：
//
//  1. 标签与前缀 key 完全相同：多条命中取最长的 key，即最具体的分组前缀；
//  2. 没有精确命中时，标签与服务名（key 第一个点之前的部分）相同即可匹配，
//     兜底只带服务标签的路由；多条命中按字典序取第一个，即服务级 key。
func (c Config) prefixFor(tags []string) string {
	if len(c.Prefixes) == 0 || len(tags) == 0 {
		return ""
	}
	keys := make([]string, 0, len(c.Prefixes))
	for key := range c.Prefixes {
		keys = append(keys, key)
	}
	sortStrings(keys)
	best := ""
	for _, key := range keys {
		if len(key) <= len(best) {
			continue
		}
		for _, tag := range tags {
			if tag == key {
				best = key
				break
			}
		}
	}
	if best != "" {
		return normalizePrefix(c.Prefixes[best])
	}
	for _, key := range keys {
		module := key
		if i := strings.IndexByte(key, '.'); i >= 0 {
			module = key[:i]
		}
		for _, tag := range tags {
			if tag == module {
				return normalizePrefix(c.Prefixes[key])
			}
		}
	}
	return ""
}

// routePath returns the deployment path of one route. By default the path is
// the prefix Group.Add stamped onto the descriptor plus the group-relative
// remainder, i.e. exactly what the client sends. A Config.Prefixes entry that
// matches the route's tags replaces the stamped prefix but keeps the remainder;
// this is how the docgen CLI -prefix override publishes the same routes under
// another base. Ungrouped routes take Config.Prefixes as their prefix.
// routePath 返回一条路由的部署路径。默认路径是 Group.Add 写入描述符的前缀加
// 分组内剩余路径，与客户端发出的路径完全一致。Config.Prefixes 命中该路由标签时
// 替换 stamped 前缀但保留剩余路径，docgen CLI 的 -prefix 覆盖据此把同一组路由
// 发布到另一个基址；未分组路由直接以 Config.Prefixes 为前缀。
func (c Config) routePath(spec endpoint.Spec) string {
	configured := c.prefixFor(spec.Tags)
	if spec.Prefix == "" {
		return endpoint.JoinPath(configured, spec.Path)
	}
	stamped := normalizePrefix(spec.Prefix)
	remainder := trimPathPrefix(spec.Path, stamped)
	if configured == "" {
		return endpoint.JoinPath(stamped, remainder)
	}
	return endpoint.JoinPath(configured, remainder)
}

// trimPathPrefix removes the stamped prefix from a path that already contains
// it, so the remainder can be attached to another base. A path that does not
// start with the prefix at a segment boundary is returned unchanged.
// trimPathPrefix 从已包含 stamped 前缀的路径里去掉该前缀，便于把剩余路径挂到
// 另一个基址；不以该前缀开头（按段边界比较）的路径原样返回。
func trimPathPrefix(path, prefix string) string {
	if path == prefix {
		return ""
	}
	if strings.HasPrefix(path, prefix+"/") {
		return strings.TrimPrefix(path, prefix)
	}
	return path
}

func securitySchemes(cfg Config, needAuth bool) map[string]any {
	if len(cfg.SecuritySchemes) > 0 {
		out := make(map[string]any, len(cfg.SecuritySchemes))
		for name, scheme := range cfg.SecuritySchemes {
			item := map[string]any{"type": scheme.Type}
			if scheme.Scheme != "" {
				item["scheme"] = scheme.Scheme
			}
			if scheme.BearerFormat != "" {
				item["bearerFormat"] = scheme.BearerFormat
			}
			if scheme.Name != "" {
				item["name"] = scheme.Name
			}
			if scheme.In != "" {
				item["in"] = scheme.In
			}
			out[name] = item
		}
		return out
	}
	if !needAuth {
		return nil
	}
	return map[string]any{
		DefaultSecurityScheme: map[string]any{
			"type":         "http",
			"scheme":       "bearer",
			"bearerFormat": "JWT",
		},
	}
}

func commonEnvelope() map[string]any {
	return map[string]any{
		"type":     "object",
		"required": []any{"code", "msg"},
		"properties": map[string]any{
			"code": map[string]any{"type": "integer", "format": "int32", "example": 0},
			"msg":  map[string]any{"type": "string", "example": "success"},
			"req_id": map[string]any{
				"type": "string",
			},
			"details": map[string]any{
				"type":                 "object",
				"additionalProperties": map[string]any{"type": "string"},
			},
		},
	}
}

func commonErrorEnvelope() map[string]any {
	return map[string]any{
		"type":     "object",
		"required": []any{"code", "msg", "data"},
		"properties": map[string]any{
			"code": map[string]any{"type": "integer", "format": "int32", "example": 40401},
			"msg":  map[string]any{"type": "string", "example": "order not found"},
			"data": map[string]any{"nullable": true, "example": nil},
			"req_id": map[string]any{
				"type":    "string",
				"example": sampleRequestID,
			},
			"details": map[string]any{
				"type":                 "object",
				"additionalProperties": map[string]any{"type": "string"},
			},
		},
	}
}
